-- BaseDatos.sql
-- Crea las dos bases del proyecto y carga la data.
-- Postgres ejecuta este script solo la primera vez que se crea el volumen,
-- al hacer docker compose up --build.
--
--   clientes_db  -> servicio de clientes (persona, cliente)
--   cuentas_db   -> servicio de cuentas  (cliente_ref, cuenta, movimiento)

CREATE DATABASE clientes_db;
CREATE DATABASE cuentas_db;


-- ============================ clientes_db ============================
\connect clientes_db

CREATE TABLE IF NOT EXISTS persona (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(255) NOT NULL,
    genero          VARCHAR(20),
    edad            INTEGER,
    identificacion  VARCHAR(50) NOT NULL UNIQUE,
    direccion       VARCHAR(255),
    telefono        VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS cliente (
    id           BIGINT PRIMARY KEY REFERENCES persona (id),
    cliente_id   VARCHAR(50) NOT NULL UNIQUE,
    contrasena   VARCHAR(255) NOT NULL,
    estado       BOOLEAN NOT NULL
);


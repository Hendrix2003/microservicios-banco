-- ============================ cuentas_db ============================
\connect cuentas_db

-- copia local de clientes, en runtime se actualiza con los eventos de rabbitmq
CREATE TABLE IF NOT EXISTS cliente_ref (
    cliente_id      VARCHAR(50) PRIMARY KEY,
    nombre          VARCHAR(255),
    identificacion  VARCHAR(50),
    estado          BOOLEAN
);

CREATE TABLE IF NOT EXISTS cuenta (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_cuenta     VARCHAR(50) NOT NULL UNIQUE,
    tipo_cuenta       VARCHAR(20) NOT NULL,
    saldo_inicial     NUMERIC(19,2) NOT NULL,
    saldo_disponible  NUMERIC(19,2) NOT NULL,
    estado            BOOLEAN NOT NULL,
    cliente_id        VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS movimiento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha            TIMESTAMP NOT NULL,
    tipo_movimiento  VARCHAR(20) NOT NULL,
    valor            NUMERIC(19,2) NOT NULL,
    saldo            NUMERIC(19,2) NOT NULL,
    cuenta_id        BIGINT NOT NULL REFERENCES cuenta (id)
);

